        self.assertEqual(_pnpm_key("/openai/4.20.1_zod@3.22.4"), ("openai", "4.20.1"))  # v5
        self.assertEqual(_pnpm_key("/@langchain/core/0.1.17"), ("@langchain/core", "0.1.17"))  # v5 scoped


