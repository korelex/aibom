class Repo:
    """A temporary folder built from {path: text}."""

    def __init__(self, files):
        self.tmp = tempfile.TemporaryDirectory()
        for rel, text in files.items():
            path = os.path.join(self.tmp.name, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(textwrap.dedent(text).lstrip("\n"))

    def scan(self):
        return find(self.tmp.name, triage(self.tmp.name))

    def close(self):
        self.tmp.cleanup()


def by_name(result, name, version=None):
    hits = [c for c in result["packages"] if c["name"] == name and (version is None or c["version"] == version)]
    assert len(hits) == 1, f"{name} {version}: {[(c['name'], c['version']) for c in result['packages']]}"
    return hits[0]


class Case(unittest.TestCase):
    files = {}

    def setUp(self):
        self.repo = Repo(self.files)
        self.result = self.repo.scan()

    def tearDown(self):
        self.repo.close()

    def pkg(self, name, version=None):
        return by_name(self.result, name, version)


class Requirements(Case):
    files = {
        "requirements.txt": """
            # the app
            openai==1.30.0
            langchain-community>=0.0.20  # a range, not a pin
            anthropic[vertex]==0.25.0 ; python_version >= "3.9"
            transformers==4.30.0 \\
                --hash=sha256:aaaa
            -e git+https://github.com/example/local.git#egg=local
            --index-url https://pypi.org/simple
            -r requirements-dev.txt
            this is not a requirement !!!
            """,
        "requirements-dev.txt": """
            pytest==8.0.0
            langsmith==0.1.0
            """,
    }

    def test_exact_pins_ranges_extras_markers_and_hashes(self):
        self.assertEqual((self.pkg("openai")["version"], self.pkg("openai")["direct"]), ("1.30.0", True))
        community = self.pkg("langchain-community")
        self.assertEqual((community["version"], community["requested"]), ("", [">=0.0.20"]))
        self.assertEqual(self.pkg("anthropic")["version"], "0.25.0")
        self.assertEqual(self.pkg("transformers")["version"], "4.30.0")  # a continued line with --hash

    def test_line_numbers_point_at_the_entry(self):
        self.assertEqual(self.pkg("openai")["evidence"][0]["line"], 2)
        self.assertEqual(self.pkg("transformers")["evidence"][0]["line"], 5)

    def test_included_files_are_followed(self):
        self.assertEqual(self.pkg("langsmith")["evidence"][0]["file"], "requirements-dev.txt")

    def test_only_ai_packages_are_reported_but_all_are_counted(self):
        names = {c["name"] for c in self.result["packages"]}
        self.assertNotIn("pytest", names)
        self.assertEqual(self.result["summary"]["packages_read"], 6)  # openai, langchain-community, anthropic, transformers, pytest, langsmith
        self.assertEqual(self.result["problems"], [])


