class PackageLock(Case):
    files = {
        "package.json": json.dumps({"name": "web", "workspaces": ["apps/*"], "dependencies": {"openai": "^4.20.0"},
                                    "devDependencies": {"@langchain/core": "0.2.0"}}, indent=2),
        "apps/bot/package.json": json.dumps({"name": "bot", "dependencies": {"@anthropic-ai/sdk": "^0.20.0", "web": "workspace:*"}}, indent=2),
        "package-lock.json": json.dumps({"name": "web", "lockfileVersion": 3, "packages": {
            "": {"name": "web", "workspaces": ["apps/*"], "dependencies": {"openai": "^4.20.0"}, "devDependencies": {"@langchain/core": "0.2.0"}},
            "apps/bot": {"name": "bot", "dependencies": {"@anthropic-ai/sdk": "^0.20.0"}},
            "node_modules/openai": {"version": "4.20.1"},
            "node_modules/@langchain/core": {"version": "0.2.0", "dev": True},
            "node_modules/@anthropic-ai/sdk": {"version": "0.20.5"},
            "node_modules/langchain/node_modules/openai": {"version": "4.10.0"},
            "node_modules/bot": {"resolved": "apps/bot", "link": True},
        }}, indent=2),
    }

    def test_v3(self):
        self.assertEqual((self.pkg("openai", "4.20.1")["direct"], self.pkg("openai", "4.20.1")["requested"]), (True, ["^4.20.0"]))
        self.assertIs(self.pkg("openai", "4.10.0")["direct"], False)  # a second copy, inside another package
        self.assertEqual(self.pkg("@langchain/core")["scope"], "dev")
        self.assertIs(self.pkg("@anthropic-ai/sdk")["direct"], True)  # a direct dependency of a workspace member

    def test_workspace_links_and_local_packages_are_skipped(self):
        self.assertNotIn("bot", {c["name"] for c in self.result["packages"]})

    def test_scoped_purl(self):
        self.assertEqual(self.pkg("@anthropic-ai/sdk")["purl"], "pkg:npm/%40anthropic-ai/sdk@0.20.5")


